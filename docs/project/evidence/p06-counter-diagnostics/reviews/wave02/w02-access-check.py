from pathlib import Path
import shlex
import subprocess
import tempfile

SOURCE = Path('/workspace/scratch/98908dfa3444/AI-GPU')
LOG = Path('/workspace/scratch/98908dfa3444/w02-access-validation.log')
ACCESS = SOURCE / 'tests/unittest/checked_counters'


def run(argv, cwd):
    result = subprocess.run(argv, cwd=cwd, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, timeout=60)
    with LOG.open('a') as log:
        log.write('$ ' + shlex.join(argv) + '\n' + result.stdout
                  + '\nexit=' + str(result.returncode) + '\n')
    if result.returncode:
        raise RuntimeError(result.stdout[-8000:])
    return result.stdout


def compile_flags(words):
    result = []
    i = 1
    while i < len(words):
        if words[i] in ('-c', '-o', '-MF'):
            i += 2
        elif words[i] in ('-MMD', '-MP'):
            i += 1
        else:
            result.append(words[i])
            i += 1
    return result


with tempfile.TemporaryDirectory(prefix='counter-access-syntax-') as temporary:
    root = Path(temporary)
    for mode, define in [('ordinary', ''), ('checked', '-DSIMX_CHECKED_COUNTERS=1')]:
        build = root / mode
        build.mkdir()
        run([str(SOURCE / 'configure'), '--xlen=64', '--profile=p02-tfr',
             '--osversion=ubuntu/focal', f'--tooldir={root / "unused-tools"}'], build)
        unit = build / 'sim/simx'
        make = ['make', '--no-print-directory', '-f', 'checked_counters.mk',
                'PERF=1', 'PROFILE=p02-tfr', 'CXX=/usr/bin/g++', f'CONFIGS={define}']
        transcript = run(make + ['-n', str(unit / 'checked_counters_test')], unit)
        records = [shlex.split(line) for line in transcript.splitlines()
                   if line.startswith('/usr/bin/g++ ')]
        compiles = [record for record in records if '-c' in record]
        links = [record for record in records if '-c' not in record]
        assert len(compiles) == 45, len(compiles)
        assert len(links) == 1, len(links)
        assert all('-fno-access-control' not in record for record in records)
        common_flags = compile_flags(compiles[0])
        assert all(compile_flags(record) == common_flags for record in compiles)
        originals = ['socket.o', 'mem/cache.o', 'mem/memory.o', 'tcu/tcu_tbuf.o']
        assert all(str(unit / 'obj' / path) not in links[0] for path in originals)
        generated = unit / 'obj/tests/checked_counters/access_tcu.generated.cpp'
        run(make + [str(generated)], unit)
        assert generated.read_bytes() == ((SOURCE / 'sim/simx/tcu/tcu_tbuf.cpp').read_bytes()
                                          + b'\n' + (ACCESS / 'access_tcu.cpp').read_bytes())
        selected = []
        for record in compiles:
            source = Path(record[record.index('-c') + 1])
            if source.parent == ACCESS or source == generated:
                if source.name == 'main.cpp':
                    continue
                selected.append(source)
                run(['/usr/bin/g++', *compile_flags(record), '-fsyntax-only', str(source)], unit)
        assert len(selected) == 5, selected
        if mode == 'ordinary':
            run(['/usr/bin/g++', *common_flags, '-fsyntax-only',
                 str(SOURCE / 'sim/simx/tcu/tcu_tbuf.cpp')], unit)
        with LOG.open('a') as log:
            log.write(f'PASS {mode}: five access TUs syntax; 45 exact-flag compile records; '
                      'one link with four originals absent; generated bytes exact.\n')
        print(f'PASS {mode}: five access TUs syntax and 45-TU make dry run', flush=True)

print(LOG)
