"""Exercise the public tensor API with the actual Vortex RISC-V C++ compiler.

Run from a freshly configured build directory, for example::

    python3 /source/ci/project/p02_api_compile.py --build-dir "$PWD" \
        --tools-dir /tools --output /new/api-compile-packet

Every translation unit forces sizeof(WMMA) and sizeof(WGMMA). Negative cases
qualify only when both contexts report the exact intended static assertion;
toolchain, configuration and unrelated C++ errors are failures. This is compiler
boundary evidence, not execution of instructions or a hardware trap test.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import sys

import baseline_process
from baseline_process import GIB, MIB, run_bounded


INPUT_DIAGNOSTIC = "TCU input format is not enabled in the native TFR configuration"
OUTPUT_DIAGNOSTIC = "TCU output type must be fp32 (int32 for integer inputs)"
GUARDS = ("FP16", "TF32", "FP8", "FP4", "INT8", "INT4", "MX", "MXFP4", "NVFP4")
BACKENDS = ("DPI", "DSP", "BHF", "TFR", "FPNEW")
CONTEXTS = ("wmma_context", "wgmma_context")
TIMEOUT_SECONDS = 30
MIN_FREE_BYTES = 15 * GIB
DEPENDENCY_TARGET = "p02_dependencies"
MAX_DEPENDENCIES = 4096
MAX_DEPENDENCY_BYTES = 64 * MIB
BOUNDARY = (
    "Actual RISC-V C++ compile boundary only; no kernel execution, numerical "
    "datapath verification, hardware trap, vendor emulation or physical device result."
)


@dataclass(frozen=True)
class Case:
    name: str
    input_type: str
    output_type: str = "fp32"
    enabled: tuple[str, ...] = ()
    backend: str = "TFR"
    diagnostic: str | None = None


def matrix() -> tuple[Case, ...]:
    """Forty-seven cases, each independently instantiating both API contexts."""
    cases = []
    for input_type, guard in (
            ("fp16", "FP16"), ("bf16", "FP16"), ("tf32", "TF32"),
            ("fp8", "FP8"), ("bf8", "FP8"), ("int8", "INT8"),
            ("uint8", "INT8"), ("int4", "INT4"), ("uint4", "INT4")):
        output = "int32" if input_type.startswith(("int", "uint")) else "fp32"
        cases.append(Case(input_type + "_enabled", input_type, output, (guard,)))
        cases.append(Case(input_type + "_disabled", input_type, output,
                          diagnostic=INPUT_DIAGNOSTIC))
    for input_type, prerequisites in (
            ("mxfp8", ("FP8", "MX")), ("mxbf8", ("FP8", "MX")),
            ("mxfp4", ("FP8", "MX", "FP4", "MXFP4")),
            ("nvfp4", ("FP8", "MX", "FP4", "NVFP4"))):
        cases.append(Case(input_type + "_enabled", input_type, enabled=prerequisites))
        for guard in prerequisites:
            cases.append(Case(input_type + "_without_" + guard.lower(), input_type,
                              enabled=tuple(g for g in prerequisites if g != guard),
                              diagnostic=INPUT_DIAGNOSTIC))
    for input_type in ("fp32", "reserved6", "reserved15", "int32"):
        output = "int32" if input_type == "int32" else "fp32"
        cases.append(Case(input_type + "_unsupported", input_type, output, GUARDS,
                          diagnostic=INPUT_DIAGNOSTIC))
    for input_type, output, guard in (
            ("fp16", "fp16", "FP16"), ("bf16", "bf16", "FP16"),
            ("fp16", "int32", "FP16"), ("int8", "fp32", "INT8"),
            ("uint4", "uint8", "INT4")):
        cases.append(Case(input_type + "_invalid_output_" + output,
                          input_type, output, (guard,), diagnostic=OUTPUT_DIAGNOSTIC))
    # The added restriction is scoped to native TFR. Each other backend keeps
    # its existing public type-instantiation behavior even with TFR guards off.
    for backend, input_type in (("DPI", "fp32"), ("DSP", "fp16"),
                                ("BHF", "bf16"), ("FPNEW", "tf32")):
        cases.append(Case("compatibility_" + backend.lower(), input_type, backend=backend))
    assert len(cases) == 47 and len({c.name for c in cases}) == len(cases)
    return tuple(cases)


def config_flags(case: Case, xlen: int) -> list[str]:
    # ENABLE=0 still satisfies #ifdef; disabled families must use DISABLE.
    return ["-DVX_CFG_XLEN=" + str(xlen), "-DVX_CFG_NUM_THREADS=8",
            "-DVX_CFG_EXT_TCU_ENABLE", "-DVX_CFG_TCU_WGMMA_ENABLE",
            "-DVX_CFG_TCU_TYPE_" + case.backend] + [
                "-DVX_CFG_TCU_" + guard + ("_ENABLE" if guard in case.enabled else "_DISABLE")
                for guard in GUARDS]


def case_source(case: Case, xlen: int) -> str:
    lines = ["// Generated by p02_api_compile.py; compile only.",
             "#include <VX_config.h>",
             "#if !defined(__clang__) || !defined(__riscv) || __riscv_xlen != " + str(xlen),
             '#error "P02 requires the configured RISC-V Clang target"', "#endif"]
    for backend in BACKENDS:
        test = "!defined" if backend == case.backend else "defined"
        lines.extend([f"#if {test}(VX_CFG_TCU_TYPE_{backend})",
                      '#error "P02 backend configuration mismatch"', "#endif"])
    for guard in GUARDS:
        test = "!defined" if guard in case.enabled else "defined"
        mirror = "1" if guard in case.enabled else "0"
        lines.extend([f"#if {test}(VX_CFG_TCU_{guard}_ENABLE) || "
                      f"VX_CFG_TCU_{guard}_ENABLED != {mirror}",
                      f'#error "P02 {guard} configuration mismatch"', "#endif"])
    lines.extend(["#include <vx_tensor.h>", "using namespace vortex::tensor;",
                  "struct reserved6 : fp32 { static constexpr uint32_t id = 6; };",
                  "struct reserved15 : fp32 { static constexpr uint32_t id = 15; };"])
    for context in CONTEXTS:
        lines.append(f"using {context}_probe = {context}<8, {case.input_type}, {case.output_type}>;")
        lines.append(f'static_assert(sizeof({context}_probe) > 0, "P02 full context instantiation");')
    return "\n".join(lines) + "\n"


def judge_compile(case: Case, result: dict, log: str, header: Path) -> tuple[bool, str]:
    """Fail closed on budget stops, arbitrary failures and incomplete diagnostics."""
    if not result.get("process_started") or not result.get("cleanup_complete"):
        return False, "compiler did not start or process cleanup was incomplete"
    if case.diagnostic is None:
        if result.get("outcome") == "pass" and result.get("exit_code") == 0:
            return True, "both complete contexts compiled"
        return False, "positive case failed: " + str(result.get("reason"))
    if (result.get("outcome") != "fail" or result.get("exit_code") != 1
            or result.get("reason") != "nonzero_exit"):
        return False, "expected a normal compiler rejection, not a tool or resource failure"
    # Error lines must be assertions in the actual public header, not quoted
    # source text or diagnostics from an unrelated file. Keep each following
    # instantiation-note block attached to its assertion.
    errors = list(re.finditer(r"^.*(?:fatal error|error):.*$", log, re.MULTILINE))
    if not errors:
        return False, "no compiler error diagnostic"
    seen = set()
    for index, error in enumerate(errors):
        parsed = re.fullmatch(r"(.+?):[0-9]+:[0-9]+: error: (.*)", error.group())
        if (parsed is None or Path(parsed[1]).resolve() != header.resolve()
                or not parsed[2].startswith("static assertion failed")
                or not parsed[2].endswith(": " + case.diagnostic)):
            return False, "unexpected compiler diagnostic: " + error.group()
        end = errors[index + 1].start() if index + 1 < len(errors) else len(log)
        block = log[error.end():end]
        for context in CONTEXTS:
            if re.search(r"note: in instantiation of template class '"
                         r"(?:vortex::tensor::)?" + context + r"<", block):
                seen.add(context)
    if seen != set(CONTEXTS):
        return False, "expected assertion was not observed for both contexts"
    return True, "both complete contexts rejected by the exact expected assertion"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(MIB), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_json(path: Path, value) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def make_setting(text: str, name: str) -> str:
    matches = re.findall(r"^" + re.escape(name) + r"[ \t]*\?=[ \t]*(.*?)[ \t]*$", text, re.MULTILINE)
    if len(matches) != 1 or "$" in matches[0]:
        raise ValueError("generated config.mk must have one literal " + name + " setting")
    return matches[0]


def parse_dependencies(text: str, cwd: Path, required: tuple[Path, ...]) -> tuple[Path, ...]:
    """Read one compiler -M/-MD rule, including system headers, without make expansion.

    Reject diagnostics, extra rules, unsupported escapes and truncated output;
    shlex is inappropriate because make escapes spaces, hashes and dollars.
    Keep the compiler's lookup paths as well as their resolved identities so a
    symlink change cannot silently select different contents.
    """
    if len(text.encode("utf-8")) > MIB or not text.endswith("\n"):
        raise ValueError("dependency output is oversized or incomplete")
    logical = text.replace("\\\n", "")
    if logical.count("\n") != 1 or not logical.startswith(DEPENDENCY_TARGET + ": "):
        raise ValueError("dependency output must contain exactly the requested rule")
    body = logical[len(DEPENDENCY_TARGET) + 2:-1]
    tokens, token = [], []
    index = 0
    while index < len(body):
        char = body[index]
        if char in " \t":
            if token:
                tokens.append("".join(token))
                token = []
        elif char == "\\":
            index += 1
            if index >= len(body) or body[index] not in " \t#\\":
                raise ValueError("unsupported dependency escape")
            token.append(body[index])
        elif char == "$":
            index += 1
            if index >= len(body) or body[index] != "$":
                raise ValueError("dependency output contains a make expansion")
            token.append("$")
        elif char in ":#\r\0":
            raise ValueError("dependency output contains unsupported make syntax")
        else:
            token.append(char)
        index += 1
    if token:
        tokens.append("".join(token))
    if not tokens or len(tokens) > MAX_DEPENDENCIES:
        raise ValueError("dependency output has no inputs or exceeds the input limit")
    paths = tuple(dict.fromkeys(path if path.is_absolute() else cwd / path
                                for path in map(Path, tokens)))
    if any(not path.is_file() for path in paths):
        raise ValueError("dependency output names a missing or non-file input")
    resolved = {path.resolve(strict=True) for path in paths}
    if any(path.resolve(strict=True) not in resolved for path in required):
        raise ValueError("dependency output omits a required translation unit or public header")
    return paths


def identity_drift(identities: dict) -> list[str]:
    drift = []
    for name, item in identities.items():
        path = Path(item["path"])
        try:
            unchanged = (str(path.resolve(strict=True)) == item["realpath"]
                         and sha256(path) == item["sha256"])
        except OSError:
            unchanged = False
        if not unchanged:
            drift.append(name)
    return drift


def update_counts(report: dict) -> None:
    launched = [case for case in report["cases"]
                if case.get("compile", {}).get("process_started") is True]
    report["launched_cases"] = len(launched)
    report["passed_cases"] = sum(case["outcome"] == "pass" for case in launched)
    report["failed_cases"] = len(launched) - report["passed_cases"]
    report["not_run_cases"] = report["planned_cases"] - len(launched)


def execute(argv: list[str], cwd: Path, env: dict, directory: Path, label: str) -> dict:
    log = directory / (label + ".log")
    record = {"argv": argv, "cwd": str(cwd), "environment": env, "log": str(log),
              "timeout_seconds": TIMEOUT_SECONDS}
    write_json(directory / (label + ".command.json"), record)
    record.update(run_bounded(argv, cwd, env, log, timeout_seconds=TIMEOUT_SECONDS,
                              min_free_bytes=MIN_FREE_BYTES, max_log_bytes=MIB,
                              max_rss_bytes=GIB, resource_paths=(directory,)))
    write_json(directory / (label + ".command.json"), record)
    return record


def require_success(record: dict) -> str:
    if (record["outcome"] != "pass" or not record["cleanup_complete"]
            or not record["process_started"] or record["exit_code"] != 0):
        raise ValueError("command failed: " + record["log"] + " (" + str(record["reason"]) + ")")
    return Path(record["log"]).read_text(encoding="utf-8", errors="strict")


def snapshot(paths: dict[str, Path], output: Path) -> dict:
    identities = {}
    for name, path in sorted(paths.items()):
        target = output / "snapshots" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
        identities[name] = {"path": str(path), "realpath": str(path.resolve(strict=True)),
                            "sha256": sha256(target),
                            "snapshot": str(target), "size_bytes": target.stat().st_size}
    return identities


def run(build: Path, tools: Path, output: Path) -> dict:
    if Path.cwd().resolve() != build:
        raise ValueError("run this suite from --build-dir (a freshly configured generated tree)")
    config_mk = build / "config.mk"
    text = config_mk.read_text(encoding="utf-8")
    source = Path(make_setting(text, "VORTEX_HOME")).resolve(strict=True)
    xlen = int(make_setting(text, "XLEN"))
    if xlen not in (32, 64) or source == build:
        raise ValueError("a separate generated RV32 or RV64 build tree is required")
    compiler = tools / "llvm-vortex/bin/clang++"
    gnu = tools / f"riscv{xlen}-gnu-toolchain"
    sysroot = gnu / f"riscv{xlen}-unknown-elf"
    generator = build / "ci/gen_config.py"
    if not compiler.is_file() or not sysroot.is_dir():
        raise ValueError("Vortex clang++ and the configured RISC-V GNU sysroot are required")
    if sha256(generator) != sha256(source / "ci/gen_config.py"):
        raise ValueError("generated gen_config.py is stale; re-run configure")
    if make_setting(text, "PROFILE"):
        raise ValueError("use a build configured without PROFILE for this explicit format matrix")
    output.mkdir(parents=False, exist_ok=False)
    (output / "tmp").mkdir()
    environment = {"PATH": os.defpath, "LC_ALL": "C", "XLEN": str(xlen),
                   "TMPDIR": str(output / "tmp")}
    report = {"schema_version": 1, "outcome": "fail", "boundary": BOUNDARY,
              "started_utc": datetime.now(timezone.utc).isoformat(),
              "build_dir": str(build), "source_dir": str(source), "tools_dir": str(tools),
              "xlen": xlen, "contexts_per_case": list(CONTEXTS), "planned_cases": 47,
              "positive_cases": sum(case.diagnostic is None for case in matrix()),
              "negative_cases": sum(case.diagnostic is not None for case in matrix()),
              "limits": {"timeout_seconds_per_command": TIMEOUT_SECONDS,
                         "max_log_bytes": MIB, "max_rss_bytes": GIB,
                         "min_free_bytes": MIN_FREE_BYTES,
                         "max_dependencies": MAX_DEPENDENCIES,
                         "max_dependency_bytes": MAX_DEPENDENCY_BYTES}, "cases": []}
    report_path = output / "report.json"
    write_json(report_path, report)
    try:
        paths = {"source/VX_config.toml": source / "VX_config.toml",
                 "source/VX_types.toml": source / "VX_types.toml",
                 "source/ci/gen_config.py": source / "ci/gen_config.py",
                 "runner/p02_api_compile.py": Path(__file__).resolve(),
                 "runner/baseline_process.py": Path(baseline_process.__file__).resolve(),
                 "build/config.mk": config_mk, "build/ci/gen_config.py": generator,
                 "build/sw/VX_config.h": build / "sw/VX_config.h",
                 "build/sw/VX_types.h": build / "sw/VX_types.h"}
        report["identities"] = snapshot(paths, output)
        report["compiler"] = {"path": str(compiler), "realpath": str(compiler.resolve()),
                              "sha256": sha256(compiler), "sysroot": str(sysroot)}
        report["compiler_version"] = require_success(execute(
            [str(compiler), "--version"], build, environment, output, "compiler-version"))
        resource_text = require_success(execute(
            [str(compiler), "-print-resource-dir"], build, environment, output, "compiler-resource-dir"))
        resource_dir = Path(resource_text.strip())
        if len(resource_text.splitlines()) != 1 or not resource_dir.is_absolute() or not resource_dir.is_dir():
            raise ValueError("compiler did not identify one existing resource directory")
        report["compiler"]["resource_dir"] = str(resource_dir)
        for label, argv in (("source-head", ["git", "-C", str(source), "rev-parse", "HEAD"]),
                            ("source-status", ["git", "-C", str(source), "status", "--short"]),
                            ("source-diff", ["git", "-C", str(source), "diff", "--binary", "HEAD"])):
            report[label] = require_success(execute(argv, build, environment, output, label))
        # Check the generated headers against current TOML bytes before choosing
        # per-case overrides. This suite never repairs or rewrites a build tree.
        for stem in ("VX_config", "VX_types"):
            argv = [sys.executable, str(generator), "--config", str(source / (stem + ".toml")),
                    "--format", "cpp", "--output", str(output / (stem + ".h"))]
            if stem == "VX_types":
                argv.append("--resolved")
            require_success(execute(argv, build, environment, output, "regenerate-" + stem))
            if sha256(output / (stem + ".h")) != sha256(build / "sw" / (stem + ".h")):
                raise ValueError("generated " + stem + ".h is stale; re-run configure")
        common = [str(compiler), f"--target=riscv{xlen}-unknown-elf",
                  "--sysroot=" + str(sysroot), "--gcc-toolchain=" + str(gnu),
                  "-march=" + ("rv64imafd" if xlen == 64 else "rv32imaf"),
                  "-mabi=" + ("lp64d" if xlen == 64 else "ilp32f"),
                  "-Xclang", "-target-feature", "-Xclang", "+xvortex",
                  "-std=c++17", "-ferror-limit=0",
                  "-fno-color-diagnostics", "-fno-caret-diagnostics", "-D__VORTEX__",
                  "-I" + str(source / "sw/kernel/include"), "-I" + str(build / "sw"),
                  "-I" + str(build / "hw"), "-I" + str(source / "sw/common")]
        dependencies = {}
        # Resolve and probe every exact configuration before any qualifying
        # compile. -M includes GNU and Clang resource headers (unlike -MM).
        for case in matrix():
            directory = output / case.name
            directory.mkdir()
            cpp = directory / "probe.cpp"
            cpp.write_text(case_source(case, xlen), encoding="utf-8")
            requested = config_flags(case, xlen)
            entry = {**asdict(case), "outcome": "not_run", "requested_flags": requested,
                     "source": str(cpp), "source_sha256": sha256(cpp)}
            report["cases"].append(entry)
            record = execute([sys.executable, str(generator), "--config", str(source / "VX_config.toml"),
                              "--format", "cflags", "--cflags=" + " ".join(requested)],
                             build, environment, directory, "resolve-config")
            resolved = shlex.split(require_success(record))
            if not resolved or any(not flag.startswith("-D") for flag in resolved):
                raise ValueError("gen_config.py did not return resolved macro arguments")
            entry["resolved_flags"] = resolved
            entry["config_log_sha256"] = record["log_sha256"]
            record = execute(common + requested + resolved +
                             ["-M", "-MT", DEPENDENCY_TARGET, str(cpp)],
                             build, environment, directory, "dependencies")
            entry["dependency_probe"] = record
            required = (cpp, source / "sw/kernel/include/vx_tensor.h",
                        build / "sw/VX_config.h", build / "sw/VX_types.h")
            selected = parse_dependencies(require_success(record), build, required)
            if any(not any(path.is_relative_to(root) for path in selected)
                   for root in (sysroot, resource_dir)):
                raise ValueError("dependency probe omitted GNU sysroot or Clang resource headers")
            entry["dependencies"] = [str(path) for path in selected]
            dependencies.update((str(path), path) for path in selected)
            if (len(dependencies) > MAX_DEPENDENCIES
                    or sum(path.stat().st_size for path in dependencies.values()) > MAX_DEPENDENCY_BYTES):
                raise ValueError("selected dependencies exceed the snapshot budget")
        report["include_dependencies"] = snapshot(
            {f"includes/{index:04d}": path for index, path in enumerate(dependencies.values())}, output)
        report["dependency_count"] = len(dependencies)
        write_json(report_path, report)
        for case, entry in zip(matrix(), report["cases"]):
            cpp = Path(entry["source"])
            directory = cpp.parent
            requested, resolved = entry["requested_flags"], entry["resolved_flags"]
            depfile = directory / "compile.d"
            # Preserve DISABLE flags alongside the resolved values so the
            # generated unresolved VX_config.h cannot re-enable a default.
            record = execute(common + requested + resolved +
                             ["-fsyntax-only", "-MD", "-MF", str(depfile),
                              "-MT", DEPENDENCY_TARGET, str(cpp)],
                             build, environment, directory, "compile")
            entry["compile"] = record
            log = (Path(record["log"]).read_text(encoding="utf-8", errors="replace")
                   if record["process_started"] else "")
            passed, reason = judge_compile(case, record, log, source / "sw/kernel/include/vx_tensor.h")
            entry.update(outcome="fail" if record["process_started"] else "not_run", reason=reason)
            if record.get("reason") not in (None, "nonzero_exit") or not record["cleanup_complete"]:
                raise ValueError("compiler process or resource failure; remaining cases not run")
            if record["process_started"]:
                if depfile.stat().st_size > MIB:
                    raise ValueError("compile dependency output exceeds the log budget")
                actual = parse_dependencies(depfile.read_text(encoding="utf-8"), build, (cpp,))
                entry["compile_dependencies_sha256"] = sha256(depfile)
                if {str(path) for path in actual} != set(entry["dependencies"]):
                    entry.update(outcome="fail", reason="compiler include selection changed after dependency probe")
                    raise ValueError(entry["reason"])
            entry["outcome"] = "pass" if passed else "fail"
            write_json(report_path, report)
            print(f"{case.name}: {entry['outcome']} ({reason})", flush=True)
        drift = identity_drift({**report["identities"], **report["include_dependencies"],
                                "compiler": report["compiler"]})
        report["identity_drift"] = drift
        update_counts(report)
        if drift:
            raise ValueError("source/build/tool identity drift: " + ", ".join(drift))
        report["outcome"] = "pass" if report["passed_cases"] == report["planned_cases"] else "fail"
    except (OSError, ValueError, UnicodeError, KeyboardInterrupt) as error:
        report["error"] = str(error) or type(error).__name__
        report["outcome"] = "fail"
    finally:
        report["finished_utc"] = datetime.now(timezone.utc).isoformat()
        update_counts(report)
        write_json(report_path, report)
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, required=True)
    parser.add_argument("--tools-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="new retained evidence directory")
    args = parser.parse_args(argv)
    try:
        build = args.build_dir.resolve(strict=True)
        tools = args.tools_dir.resolve(strict=True)
        output = args.output.absolute()
        if output.parent.resolve(strict=True) != output.parent or output.exists() or output.is_symlink():
            raise ValueError("--output must be a new directory beneath an existing nonsymlink parent")
        report = run(build, tools, output)
    except (OSError, ValueError) as error:
        print("p02_api_compile: " + str(error), file=sys.stderr)
        return 2
    print("Report: " + str(output / "report.json"))
    print(BOUNDARY)
    if "error" in report:
        print(report["error"], file=sys.stderr)
    return 0 if report["outcome"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
