"""Adapt the validated tiny-model fixture into immutable native host inputs."""

from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
from pathlib import Path
import sys

import p04_model_contract as contract
import p04_reference as reference


ROOT = Path(__file__).resolve().parents[2]
HEADER_PATH = "tests/regression/ai_mlp/p04_fixtures.h"
MAX_HEADER_BYTES = 256 * 1024


def _validated_cases(root: Path) -> tuple[dict, list[dict]]:
    summary = contract.validate(root)
    data = contract._read_file(root / contract.FIXTURE_PATH, contract.MAX_DOCUMENT_BYTES)
    if hashlib.sha256(data).hexdigest() != summary["fixture_sha256"]:
        raise contract.ContractError("fixture changed after contract validation")
    fixture = contract._parse(data, "fixture")
    cases = []
    for source in fixture["cases"]:
        case = deepcopy(source)
        weights = fixture["weights"]["formats"][case["format"]]
        case["w1_words"] = list(weights["w1_words"])
        case["w2_words"] = list(weights["w2_words"])
        cases.append(case)
    return summary, cases


def load_cases(root: Path = ROOT) -> list[dict]:
    return _validated_cases(Path(root))[1]


def _array(words: list[str], indent: int) -> list[str]:
    prefix = " " * indent
    lines = [prefix + "{"]
    for offset in range(0, len(words), 8):
        lines.append(prefix + "  " + ", ".join("0x" + word + "u"
                                             for word in words[offset:offset + 8]) + ",")
    lines.append(prefix + "},")
    return lines


def render_header(root: Path = ROOT) -> str:
    summary, cases = _validated_cases(Path(root))
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by ci/project/p04_fixture_adapter.py; do not edit.",
        "", "#pragma once", "", "#include <array>", "#include <cstddef>",
        "#include <cstdint>", "#include <string_view>", "", "namespace p04 {", "",
        'inline constexpr char kModelId[] = "' + reference.MODEL_ID + '";',
        'inline constexpr char kFixtureId[] = "' + reference.FIXTURE_ID + '";',
        'inline constexpr char kFixtureSha256[] = "' + summary["fixture_sha256"] + '";',
        "", "struct NativeInputs {",
        "  std::array<uint32_t, 128> input_words;",
        "  std::array<uint32_t, 64> w1_words;",
        "  std::array<uint32_t, 16> w2_words;", "};", "",
        "struct ExpectedOutputs {",
        "  std::array<uint32_t, 128> hidden_words;",
        "  std::array<uint32_t, 64> bridge_words;",
        "  std::array<uint32_t, 64> output_words;", "};", "",
        "struct Fixture {", "  const char* id;", "  const char* format;",
        "  NativeInputs inputs;", "  ExpectedOutputs expected;", "};", "",
        "inline constexpr Fixture kFixtures[] = {",
    ]
    for case in cases:
        lines.extend(["  {", '    "' + case["id"] + '", "' + case["format"] + '",',
                      "    {"])
        for key in ("input_words", "w1_words", "w2_words"):
            lines.extend(_array(case[key], 6))
        lines.extend(["    },", "    {"])
        for key in ("hidden_words", "bridge_words", "output_words"):
            lines.extend(_array(case[key], 6))
        lines.extend(["    },", "  },"])
    lines.extend([
        "};", "", "inline constexpr size_t kCaseCount = sizeof(kFixtures) / sizeof(kFixtures[0]);",
        "", "inline constexpr const Fixture* find_case(std::string_view id) noexcept {",
        "  for (const auto& fixture : kFixtures) {", "    if (id == fixture.id) {",
        "      return &fixture;", "    }", "  }", "  return nullptr;", "}", "",
        "} // namespace p04", "",
    ])
    text = "\n".join(lines)
    if len(text.encode("utf-8")) > MAX_HEADER_BYTES:
        raise contract.ContractError("generated fixture header exceeds its size bound")
    return text


def check_header(root: Path = ROOT) -> None:
    root = Path(root)
    expected = render_header(root).encode("utf-8")
    if contract._read_file(root / HEADER_PATH, MAX_HEADER_BYTES) != expected:
        raise contract.ContractError("generated fixture header differs from the validated fixture")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="verify without writing (default)")
    modes.add_argument("--write-header", action="store_true", help="regenerate the C++ fixture header")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    try:
        if args.write_header:
            data = render_header(args.root).encode("utf-8")
            destination = contract._plain_path(args.root / HEADER_PATH)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
            print("Wrote the immutable tiny-model fixture header; no native execution.")
        else:
            check_header(args.root)
            print("Verified the tiny-model fixture adapter and header; no native execution.")
    except (OSError, ValueError) as error:
        print(f"Tiny-model fixture adapter: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
